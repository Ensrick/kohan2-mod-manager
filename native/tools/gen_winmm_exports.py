"""Generates loader/winmm_exports.inc and loader/winmm.def from tools/winmm_exports.txt.

tools/winmm_exports.txt holds one export of the 32-bit system winmm.dll per line: "<ordinal> <name>", or
"<ordinal> -" for an export that has an ordinal and no name. It was taken from `dumpbin /exports
C:\\Windows\\SysWOW64\\winmm.dll` (Windows 11 24H2: 193 exports, 192 of them named, ordinal 2 nameless). The loader
keeps every ordinal, so a program that imports by ordinal lands on the same function as with the system DLL.

Exports listed in WRAPPED are implemented by hand in loader/dllmain.cpp (they start the plugins); every other export
is a jump straight into the system DLL.

Refresh the list from another Windows build:
    py -3 tools/gen_winmm_exports.py --from-dumpbin <dumpbin /exports output>
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LIST = ROOT / 'tools' / 'winmm_exports.txt'
INC = ROOT / 'loader' / 'winmm_exports.inc'
DEF = ROOT / 'loader' / 'winmm.def'
LF = chr(10)
WRAPPED = {'timeBeginPeriod', 'timeEndPeriod', 'timeGetTime'}


def from_dumpbin(path):
    rows = []
    for line in pathlib.Path(path).read_text(encoding='utf-8', errors='replace').splitlines():
        m = re.match(r'^\s+(\d+)\s+(?:[0-9A-Fa-f]+\s+)?[0-9A-Fa-f]{8}\s+(\S+)', line)
        if m:
            rows.append((int(m.group(1)), '-' if m.group(2) == '[NONAME]' else m.group(2)))
    if not rows:
        sys.exit('no exports found in ' + str(path))
    LIST.write_text('# ordinal name ("-" = exported by ordinal only). Generated from dumpbin /exports of the 32-bit system winmm.dll.' + LF +
                    LF.join('%d %s' % r for r in sorted(rows)) + LF, encoding='ascii', newline=LF)


def main():
    if len(sys.argv) == 3 and sys.argv[1] == '--from-dumpbin':
        from_dumpbin(sys.argv[2])
    rows = []
    for line in LIST.read_text(encoding='ascii').splitlines():
        if not line.strip() or line.startswith('#'):
            continue
        ordinal, name = line.split()
        rows.append((int(ordinal), name))
    rows.sort()
    missing = WRAPPED - {name for _, name in rows}
    if missing:
        sys.exit('winmm_exports.txt lacks ' + ', '.join(sorted(missing)))

    inc = ['// GENERATED by tools/gen_winmm_exports.py from tools/winmm_exports.txt. Do not edit.',
           '// WINMM_EXPORT(index, name, ordinal) for a named export, WINMM_ORDINAL(index, ordinal) for one without a name,',
           '// WINMM_WRAPPED(index, name, ordinal) for one implemented by hand in dllmain.cpp.']
    dfile = ['; GENERATED by tools/gen_winmm_exports.py from tools/winmm_exports.txt. Do not edit.', 'LIBRARY winmm',
             'EXPORTS']
    for i, (ordinal, name) in enumerate(rows):
        if name == '-':
            inc.append('WINMM_ORDINAL(%d, %d)' % (i, ordinal))
            dfile.append('    winmm_ordinal_%d = proxy_ord_%d @%d NONAME' % (ordinal, ordinal, ordinal))
        elif name in WRAPPED:
            inc.append('WINMM_WRAPPED(%d, %s, %d)' % (i, name, ordinal))
            dfile.append('    %s = wrap_%s @%d' % (name, name, ordinal))
        else:
            inc.append('WINMM_EXPORT(%d, %s, %d)' % (i, name, ordinal))
            dfile.append('    %s = proxy_%s @%d' % (name, name, ordinal))
    inc.append('#define WINMM_EXPORT_COUNT %d' % len(rows))
    INC.write_text(LF.join(inc) + LF, encoding='ascii', newline=LF)
    DEF.write_text(LF.join(dfile) + LF, encoding='ascii', newline=LF)
    print('%d exports (%d named, %d wrapped) -> %s, %s' % (len(rows), sum(1 for r in rows if r[1] != '-'), len(WRAPPED), INC.name, DEF.name))


if __name__ == '__main__':
    main()

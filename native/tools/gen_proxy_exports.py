"""Generates loader/proxy_exports.inc and loader/proxy.def from tools/avifil32_exports.txt.

The plugin loader stands in for avifil32.dll: k2.exe imports it, it is not a KnownDLL, and nothing preloads it, so
Windows takes the copy in the game folder. (winmm.dll, the first choice, is preloaded from System32 by the Windows
compatibility shims applied to k2.exe, so a copy in the game folder is never used.) Every export of the real 32-bit
avifil32.dll is kept under its ordinal: functions jump straight into the real DLL, and the four data exports (COM
interface IDs) are copies of the GUIDs.

tools/avifil32_exports.txt is "<ordinal> <name>" per line ("-" = exported by ordinal only), from
    py -3 tools/dump_exports.py C:\\Windows\\SysWOW64\\avifil32.dll > tools/avifil32_exports.txt
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LIST = ROOT / 'tools' / 'avifil32_exports.txt'
INC = ROOT / 'loader' / 'proxy_exports.inc'
DEF = ROOT / 'loader' / 'proxy.def'
LF = chr(10)
# Data exports: the GUIDs vfw.h defines with DEFINE_AVIGUID(name, l, 0, 0): {l, 0, 0, {0xC0,0,0,0,0,0,0,0x46}}.
DATA = {'IID_IAVIFile': 0x20020, 'IID_IAVIStream': 0x20021, 'IID_IAVIStreaming': 0x20022,
        'IID_IGetFrame': 0x20023, 'IID_IAVIEditStream': 0x20024}
# COM entry points: exported PRIVATE (kept out of the import library), as the linker requires.
PRIVATE = {'DllCanUnloadNow', 'DllGetClassObject', 'DllRegisterServer', 'DllUnregisterServer'}


def main():
    rows = []
    for line in LIST.read_text(encoding='ascii').splitlines():
        if not line.strip() or line.startswith('#'):
            continue
        ordinal, name = line.split()
        rows.append((int(ordinal), name))
    rows.sort()
    inc = ['// GENERATED by tools/gen_proxy_exports.py from tools/avifil32_exports.txt. Do not edit.',
           '// PROXY_EXPORT(index, name, ordinal): a function, PROXY_ORDINAL(index, ordinal): a function without a name,',
           '// PROXY_DATA(index, name, ordinal, l): a COM interface ID {l, 0, 0, C0 00 00 00 00 00 00 46}.']
    dfile = ['; GENERATED by tools/gen_proxy_exports.py from tools/avifil32_exports.txt. Do not edit.',
             'LIBRARY avifil32', 'EXPORTS']
    for i, (ordinal, name) in enumerate(rows):
        if name == '-':
            inc.append('PROXY_ORDINAL(%d, %d)' % (i, ordinal))
            dfile.append('    proxy_ordinal_%d = proxy_ord_%d @%d NONAME' % (ordinal, ordinal, ordinal))
        elif name in DATA:
            inc.append('PROXY_DATA(%d, %s, %d, 0x%x)' % (i, name, ordinal, DATA[name]))
            dfile.append('    %s = data_%s @%d DATA' % (name, name, ordinal))
        elif name.startswith(('IID_', 'CLSID_')):
            sys.exit('unknown data export ' + name + ': add its GUID to DATA')
        else:
            inc.append('PROXY_EXPORT(%d, %s, %d)' % (i, name, ordinal))
            if name in PRIVATE:   # found by name only (COM); the linker refuses an ordinal on a PRIVATE export
                dfile.append('    %s = proxy_%s PRIVATE' % (name, name))
            else:
                dfile.append('    %s = proxy_%s @%d' % (name, name, ordinal))
    inc.append('#define PROXY_EXPORT_COUNT %d' % len(rows))
    INC.write_text(LF.join(inc) + LF, encoding='ascii', newline=LF)
    DEF.write_text(LF.join(dfile) + LF, encoding='ascii', newline=LF)
    print('%d exports (%d data) -> %s, %s' % (len(rows), sum(1 for r in rows if r[1] in DATA), INC.name, DEF.name))


if __name__ == '__main__':
    main()

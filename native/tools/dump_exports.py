"""Prints a DLL's exports as "<ordinal> <name>" lines ("-" for an export without a name), the input format of
gen_proxy_exports.py.  py -3 tools/dump_exports.py C:\\Windows\\SysWOW64\\avifil32.dll > tools/avifil32_exports.txt"""
import struct
import sys


def main(path):
    d = open(path, "rb").read()
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    magic = struct.unpack_from("<H", d, pe + 24)[0]
    opt = pe + 24
    dirs = opt + (96 if magic == 0x10B else 112)
    exp_rva, exp_size = struct.unpack_from("<II", d, dirs)
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    optsize = struct.unpack_from("<H", d, pe + 20)[0]
    secs = []
    for i in range(nsec):
        o = opt + optsize + 40 * i
        vsize, va, rsize, raw = struct.unpack_from("<IIII", d, o + 8)
        secs.append((va, max(vsize, rsize), raw))

    def off(rva):
        for va, size, raw in secs:
            if va <= rva < va + size:
                return rva - va + raw
        raise ValueError(hex(rva))

    e = off(exp_rva)
    base, nfun, nname, afun, aname, aord = struct.unpack_from("<IIIIII", d, e + 16)
    names = {}
    for i in range(nname):
        name_rva = struct.unpack_from("<I", d, off(aname) + 4 * i)[0]
        idx = struct.unpack_from("<H", d, off(aord) + 2 * i)[0]
        names[idx] = d[off(name_rva):].split(b"\0")[0].decode()
    print("# ordinal name (\"-\" = exported by ordinal only). Generated by tools/dump_exports.py from " +
          path.replace("\\", "/").split("/")[-1])
    for i in range(nfun):
        if struct.unpack_from("<I", d, off(afun) + 4 * i)[0] == 0:
            continue
        print(f"{base + i} {names.get(i, '-')}")


if __name__ == "__main__":
    main(sys.argv[1])
